package com.vibemusic.nativeapp.ytdlp

import android.content.Context
import android.webkit.CookieManager
import java.io.File
import java.security.MessageDigest
import java.util.UUID

class YtMusicAuthManager(private val context: Context) {

    val cookiesFile: File
        get() = File(context.filesDir, "yt_cookies.txt")

    private val cookieHeaderFile: File
        get() = File(context.filesDir, "yt_cookie_header.txt")

    private val authCookieNames = setOf("SAPISID", "__Secure-3PAPISID", "__Secure-1PAPISID")

    @Synchronized
    fun isLoggedIn(): Boolean {
        val webCookies = readWebViewCookiesMap()
        if (hasAuthCookie(webCookies)) {
            if (!cookiesFile.exists() || cookiesFile.length() == 0L || !cookieHeaderFile.exists()) {
                extractAndSaveCookies()
            }
            return true
        }
        return hasAuthCookieInCookiesFile()
    }

    @Synchronized
    fun createTempCookiesFile(targetDir: File? = null): File? {
        if (!isLoggedIn()) return null
        val src = cookiesFile
        if (!src.exists() || src.length() == 0L) return null
        return try {
            val dir = (targetDir ?: context.cacheDir).apply { mkdirs() }
            val dst = File(dir, "yt_cookies_${UUID.randomUUID()}.txt")
            src.copyTo(dst, overwrite = true)
            dst
        } catch (_: Exception) {
            null
        }
    }

    @Synchronized
    fun extractAndSaveCookies(): Boolean {
        val cm = try {
            CookieManager.getInstance()
        } catch (_: Exception) {
            return hasAuthCookieInCookiesFile()
        }

        val musicHeader = cm.getCookie("https://music.youtube.com").orEmpty()
        val wwwHeader = cm.getCookie("https://www.youtube.com").orEmpty()
        val ytHeader = cm.getCookie("https://youtube.com").orEmpty()
        val googleHeader = cm.getCookie("https://accounts.google.com").orEmpty()

        val ytCookies = LinkedHashMap<String, String>()
        parseCookieString(ytHeader, ytCookies)
        parseCookieString(wwwHeader, ytCookies)
        parseCookieString(musicHeader, ytCookies)

        val googleCookies = LinkedHashMap<String, String>()
        parseCookieString(googleHeader, googleCookies)

        if (!hasAuthCookie(ytCookies)) {
            return false
        }

        try {
            cm.flush()
        } catch (_: Exception) {}

        val headerString = ytCookies.entries.joinToString("; ") { "${it.key}=${it.value}" }
        try {
            cookieHeaderFile.writeText(headerString)
        } catch (_: Exception) {}

        val sb = StringBuilder()
        sb.append("# Netscape HTTP Cookie File\n")
        sb.append("# Generated by VibeMusic\n\n")
        val expires = "2147483647"

        for ((name, value) in ytCookies) {
            if (name.startsWith("__Host-")) {
                sb.append("music.youtube.com\tFALSE\t/\tTRUE\t$expires\t$name\t$value\n")
            } else {
                sb.append(".youtube.com\tTRUE\t/\tTRUE\t$expires\t$name\t$value\n")
            }
        }
        for ((name, value) in googleCookies) {
            if (name.startsWith("__Host-")) {
                sb.append("accounts.google.com\tFALSE\t/\tTRUE\t$expires\t$name\t$value\n")
            } else {
                sb.append(".google.com\tTRUE\t/\tTRUE\t$expires\t$name\t$value\n")
            }
        }

        return try {
            cookiesFile.writeText(sb.toString())
            true
        } catch (_: Exception) {
            false
        }
    }

    fun getCookieHeader(): String {
        val live = try {
            CookieManager.getInstance().getCookie("https://music.youtube.com").orEmpty()
        } catch (_: Exception) {
            ""
        }
        if (live.isNotBlank()) {
            val map = LinkedHashMap<String, String>()
            parseCookieString(live, map)
            if (hasAuthCookie(map)) {
                return live
            }
        }
        return try {
            if (cookieHeaderFile.exists()) cookieHeaderFile.readText().trim() else ""
        } catch (_: Exception) {
            ""
        }
    }

    fun buildSapisidHashHeader(origin: String = "https://music.youtube.com"): String? {
        val header = getCookieHeader()
        if (header.isBlank()) return null

        val cookies = LinkedHashMap<String, String>()
        parseCookieString(header, cookies)

        val sapisid = cookies["SAPISID"]
        val p1 = cookies["__Secure-1PAPISID"]
        val p3 = cookies["__Secure-3PAPISID"]
        val fallback = sapisid ?: p3 ?: p1 ?: return null

        val ts = System.currentTimeMillis() / 1000L
        val parts = mutableListOf<String>()
        parts += "SAPISIDHASH ${ts}_${sha1Hex("$ts ${sapisid ?: fallback} $origin")}"
        parts += "SAPISID1PHASH ${ts}_${sha1Hex("$ts ${p1 ?: fallback} $origin")}"
        parts += "SAPISID3PHASH ${ts}_${sha1Hex("$ts ${p3 ?: fallback} $origin")}"
        return parts.joinToString(" ")
    }

    @Synchronized
    fun logout() {
        try {
            if (cookiesFile.exists()) cookiesFile.delete()
        } catch (_: Exception) {}
        try {
            if (cookieHeaderFile.exists()) cookieHeaderFile.delete()
        } catch (_: Exception) {}
        try {
            val cm = CookieManager.getInstance()
            cm.removeAllCookies(null)
            cm.flush()
        } catch (_: Exception) {}
    }

    private fun readWebViewCookiesMap(): Map<String, String> {
        val map = LinkedHashMap<String, String>()
        try {
            val cm = CookieManager.getInstance()
            parseCookieString(cm.getCookie("https://www.youtube.com").orEmpty(), map)
            parseCookieString(cm.getCookie("https://music.youtube.com").orEmpty(), map)
        } catch (_: Exception) {}
        return map
    }

    private fun hasAuthCookie(cookies: Map<String, String>): Boolean {
        return authCookieNames.any { key -> !cookies[key].isNullOrBlank() }
    }

    private fun hasAuthCookieInCookiesFile(): Boolean {
        val file = cookiesFile
        if (!file.exists() || file.length() == 0L) return false
        return try {
            file.useLines { lines ->
                lines.any { line ->
                    val trimmed = line.trim()
                    if (trimmed.isEmpty() || trimmed.startsWith("#")) {
                        false
                    } else {
                        val cols = trimmed.split('\t')
                        cols.size >= 7 && authCookieNames.contains(cols[5]) && cols[6].isNotBlank()
                    }
                }
            }
        } catch (_: Exception) {
            false
        }
    }

    private fun parseCookieString(raw: String, out: MutableMap<String, String>) {
        if (raw.isBlank()) return
        for (part in raw.split(';')) {
            val trimmed = part.trim()
            val eqIdx = trimmed.indexOf('=')
            if (eqIdx > 0) {
                val k = trimmed.substring(0, eqIdx).trim()
                val v = trimmed.substring(eqIdx + 1).trim()
                if (k.isNotEmpty() && v.isNotEmpty()) {
                    out[k] = v
                }
            }
        }
    }

    private fun sha1Hex(input: String): String {
        val digest = MessageDigest.getInstance("SHA-1").digest(input.toByteArray(Charsets.UTF_8))
        return digest.joinToString("") { "%02x".format(it) }
    }
}
